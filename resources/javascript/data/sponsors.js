// automatically insert sponsors into page
(function() {
  var diamond = document.getElementById('diamond-sponsors'),
      gold = document.getElementById('gold-sponsors'),
      silver = document.getElementById('silver-sponsors'),
      bronze = document.getElementById('bronze-sponsors'),
      standard = document.getElementById('standard-sponsors');
  
  if (diamond && gold && silver && bronze && standard) {
    var i = 0,
        j = Kantan.sponsors.length,
        str = {
          diamond : '',
          gold : '',
          silver : '',
          bronze : '',
          std : ''
        };
    
    // build HTML for each sponsor
    for (; i < j; i++) {
      str[Kantan.sponsors[i].tier ? Kantan.sponsors[i].tier : 'std'] +=
        '<a href="' + (Kantan.sponsors[i].kofi ? 'https://ko-fi.com/home/coffeeshop?txid=' + Kantan.sponsors[i].kofi : Kantan.sponsors[i].github ? 'https://github.com/' + Kantan.sponsors[i].github : '#') + '" class="mini-profile" target="_blank" ' + (Kantan.sponsors[i].note ? 'title="' + Kantan.sponsors[i].note + '"' : '') + '>'+
          '<span class="mini-profile-inner">'+
            '<span class="mini-avatar"><img src="' + getPaths() + 'resources/images/avatars/' + Kantan.sponsors[i].avatar + '"></span>'+
            '<span class="mini-name">' + Kantan.sponsors[i].name + '</span>'+
          '</span>'+
        '</a>';
    }
    
    // insert HTML for each sponsor
    diamond.innerHTML = str.diamond ? str.diamond : '<p>No Diamond Sponsors, yet!</p><br>';
    gold.innerHTML = str.gold ? str.gold : '<p>No Gold Sponsors, yet!</p><br>';
    silver.innerHTML = str.silver ? str.silver : '<p>No Silver Sponsors, yet!</p><br>';
    bronze.innerHTML = str.bronze ? str.bronze : '<p>No Bronze Sponsors, yet!</p><br>';
    standard.innerHTML = str.std ? str.std : '<p>No Sponsors, yet!</p><br>';
  }
}());